# 1. Numerical Gradient Checking
# ---------------------------------------------------------------------------
def test_numerical_gradient_checking():
    """
    Validate the analytical gradients (backprop) of the actual computation graph
    against numerical finite-difference gradients.
    Since Softmax + CCE is fused, we check the gradient dL/dz at the logits layer.
    """
    np.random.seed(42)
    batch_size = 2
    num_classes = 10
    
    # 1. Create fake logits (z)
    logits = np.random.randn(batch_size, num_classes)
    
    # 2. Create one-hot targets
    y_true = np.zeros((batch_size, num_classes))
    y_true[0, 3] = 1
    y_true[1, 7] = 1
    
    # 3. Analytical Fused Gradient (dL/dz = 1/N * (probs - y_true))
    # Softmax forward
    shifted = logits - np.max(logits, axis=1, keepdims=True)
    exps = np.exp(shifted)
    probs = exps / np.sum(exps, axis=1, keepdims=True)
    
    loss_fn = CategoricalCrossEntropy()
    loss_val = loss_fn.forward(probs, y_true)
    analytical_grad = loss_fn.backward()
    
    # 4. Numerical Gradient using finite differences
    epsilon = 1e-5
    numerical_grad = np.zeros_like(logits)
    
    for i in range(batch_size):
        for j in range(num_classes):
            logits_plus = logits.copy()
            logits_plus[i, j] += epsilon
            
            logits_minus = logits.copy()
            logits_minus[i, j] -= epsilon
            
            # Loss plus
            s_plus = logits_plus - np.max(logits_plus, axis=1, keepdims=True)
            e_plus = np.exp(s_plus)
            p_plus = e_plus / np.sum(e_plus, axis=1, keepdims=True)
            loss_plus = loss_fn.forward(p_plus, y_true)
            
            # Loss minus
            s_minus = logits_minus - np.max(logits_minus, axis=1, keepdims=True)
            e_minus = np.exp(s_minus)
            p_minus = e_minus / np.sum(e_minus, axis=1, keepdims=True)
            loss_minus = loss_fn.forward(p_minus, y_true)
            
            numerical_grad[i, j] = (loss_plus - loss_minus) / (2 * epsilon)
            
    # 5. Compare
    diff = np.abs(analytical_grad - numerical_grad)
    max_diff = np.max(diff)
    
    assert max_diff < 1e-6, f"Gradient check failed! Max diff: {max_diff}"

