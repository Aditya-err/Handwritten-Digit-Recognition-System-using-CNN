# 4. Save/Load Determinism
# ---------------------------------------------------------------------------
def test_save_load_determinism(tmp_path):
    """
    Ensure loading weights back results in identical predictions.
    """
    X_test, _ = load_mnist(split='test', subset_size=5)
    
    nn1 = NeuralNetwork(seed=42)
    # Forward pass on nn1
    preds1 = nn1.predict(X_test)
    
    # Save nn1
    save_file = tmp_path / "model.npz"
    nn1.save(save_file)
    
    # Load into nn2
    nn2 = NeuralNetwork(seed=999) # different seed
    nn2.load(save_file)
    preds2 = nn2.predict(X_test)
    
    np.testing.assert_array_equal(preds1, preds2)

