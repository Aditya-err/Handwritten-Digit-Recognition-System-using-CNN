# 3. Evaluation on Test Data
# ---------------------------------------------------------------------------
def test_evaluation_test_data():
    """
    Evaluate on test data. Using pre-trained weights to measure real accuracy.
    The goal is simply to substantially exceed random guessing (10%).
    """
    X_test, y_test = load_mnist(split='test', subset_size=100)
    
    # We load the weights generated by our pre-training script
    nn = NeuralNetwork()
    weights_path = pathlib.Path(__file__).parent.parent.parent / "weights" / "model.npz"
    nn.load(weights_path)
    
    loss, accuracy = nn.evaluate(X_test, y_test)
    
    # We do NOT hardcode 90%. We just ensure it's significantly better than random guessing.
    assert accuracy > 0.30, f"Accuracy {accuracy} is too close to random guessing."

