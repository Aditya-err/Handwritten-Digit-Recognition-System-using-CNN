# 2. Overfit on small batch
# ---------------------------------------------------------------------------
def test_overfit_small_batch():
    """
    Validate that the model can severely overfit on a small dataset (50 samples).
    """
    X_train, y_train = load_mnist(split='train', subset_size=50)
    
    nn = NeuralNetwork(seed=123)
    
    epochs = 20
    learning_rate = 0.5
    
    initial_loss, initial_acc = nn.evaluate(X_train, y_train)
    
    for _ in range(epochs):
        probs = nn.forward(X_train, training=True)
        y_one_hot = np.zeros((len(y_train), 10))
        y_one_hot[np.arange(len(y_train)), y_train] = 1
        nn.loss_fn.forward(probs, y_one_hot)
        
        d_loss = nn.loss_fn.backward()
        nn.backward(d_loss)
        nn.update_weights(learning_rate)
        
    final_loss, final_acc = nn.evaluate(X_train, y_train)
    
    assert final_loss < initial_loss, f"Loss didn't decrease: {initial_loss} -> {final_loss}"
    assert final_acc > initial_acc, "Accuracy didn't improve"
    assert final_acc == 1.0, f"Expected perfect overfitting (1.0), got {final_acc}"

